/**
 * Materialise `backend/keys/` for local development, from the test fixtures.
 *
 *     npm run dev-keys
 *     npm run dev-keys -- --force
 *
 * ## Why this script has to exist
 *
 * `assertRuntimePaths` requires `TRUST_BUNDLE_PATH` and `TRUST_ROOT_PUBLIC_KEY_PATH`
 * to exist as files before the server binds a socket, and it requires them *even in
 * mock mode* — deliberately, because an API that cannot verify a signature answers
 * UNVERIFIABLE to every scan, and failing at startup is enormously better than
 * discovering that from a patient's phone. The repository ships no `keys/`
 * directory, because a trust bundle is deployment material and a checked-in one is a
 * standing invitation to run production against a development root. So a fresh clone
 * cannot start the server at all until those two files exist, and this is the script
 * that puts them there.
 *
 * ## Why the fixtures are the right source
 *
 * `tests/fixtures/fixtures.json` already contains a properly signed bundle: three
 * manufacturer keys, a real ECDSA root signature over the canonical bundle, and the
 * root public key that checks it. Two things follow from reusing it rather than
 * generating a new root here.
 *
 * The first is that `mobile/assets/trust_bundle.json` is byte-identical to that same
 * fixture, so a phone built from this repository and a server started from these
 * keys share one trust root — which means a QR code from the fixtures scans as
 * GENUINE end to end, on the phone offline and against the API online. A freshly
 * generated root would verify perfectly on the server and make every scan from the
 * app fail, for reasons that would take a long evening to find.
 *
 * The second is that this script needs no private key and generates no secret. It
 * copies public material. There is nothing here to leak.
 *
 * ## Why it refuses in production
 *
 * The private half of the fixture root is generated by a published script in this
 * repository, so anyone can sign a bundle that these keys accept. Under that root,
 * signature verification is theatre: an attacker inserts their own signing key,
 * signs it with the root everyone has, and every counterfeit they print verifies as
 * genuine. The refusal lives in the exported function rather than in the CLI, so it
 * holds however this code is reached and can be tested.
 *
 * ## Why it verifies before it commits
 *
 * The files are written to `.tmp` names, loaded back through the API's own
 * `loadTrustBundle` with `requireSignature: true`, checked for a usable key and the
 * expected root fingerprint, and only then renamed into place. A bundle whose
 * signature does not verify is worse than no bundle: the server refuses to start and
 * the error points at the trust bundle, not at whatever wrote it. Verifying with the
 * real loader means the check is exactly the one the server will perform, rather than
 * a re-implementation that could pass while the server's fails.
 */

import { mkdir, readFile, rename, unlink, writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { loadTrustBundle } from '../src/services/trust.js';

/** `backend/`, so the defaults do not depend on the caller's working directory. */
const BACKEND_ROOT = fileURLToPath(new URL('../', import.meta.url));

export const DEFAULT_FIXTURES_PATH = path.join(
  BACKEND_ROOT,
  'tests',
  'fixtures',
  'fixtures.json',
);
export const DEFAULT_OUT_DIR = path.join(BACKEND_ROOT, 'keys');

const BUNDLE_FILE = 'trust-bundle.json';
const ROOT_KEY_FILE = 'root-public.pem';

async function exists(p) {
  try {
    await access(p);
    return true;
  } catch {
    return false;
  }
}

/**
 * Write `keys/trust-bundle.json` and `keys/root-public.pem`.
 *
 * @param {{fixturesPath?: string, outDir?: string, force?: boolean,
 *          env?: Record<string, string|undefined>}} [args]
 * @returns {Promise<{bundlePath: string, rootPublicKeyPath: string,
 *                    rootFingerprint: string, summary: object}>}
 */
export async function materialiseDevKeys({
  fixturesPath = DEFAULT_FIXTURES_PATH,
  outDir = DEFAULT_OUT_DIR,
  force = false,
  env = process.env,
} = {}) {
  if (env.NODE_ENV === 'production') {
    throw new Error(
      'refusing to write development trust keys with NODE_ENV=production.\n' +
        'The private half of this root is generated by a script in this repository, ' +
        'so anyone can sign a bundle it accepts — under this root, signature ' +
        'verification proves nothing. A production deployment needs a root key ' +
        'generated on an offline machine and a bundle signed with it.',
    );
  }

  let fixtures;
  try {
    fixtures = JSON.parse(await readFile(fixturesPath, 'utf8'));
  } catch (cause) {
    throw new Error(
      `could not read the fixtures at ${fixturesPath}: ${cause?.message ?? cause}`,
    );
  }

  const bundle = fixtures.trust_bundle_signed;
  const rootPem = fixtures.root_public_key_pem;
  if (!bundle || typeof bundle !== 'object' || typeof rootPem !== 'string') {
    throw new Error(
      `${fixturesPath} has no trust_bundle_signed / root_public_key_pem. It is not ` +
        'the TrueMed fixture file, or it has been regenerated with a different shape.',
    );
  }
  if (typeof bundle.root_signature !== 'string' || bundle.root_signature === '') {
    throw new Error(
      'the fixture bundle carries no root_signature, so nothing written from it ' +
        'would load with TRUST_REQUIRE_SIGNATURE=1 (the default)',
    );
  }

  const bundlePath = path.join(outDir, BUNDLE_FILE);
  const rootPublicKeyPath = path.join(outDir, ROOT_KEY_FILE);

  if (!force) {
    for (const target of [bundlePath, rootPublicKeyPath]) {
      if (await exists(target)) {
        throw new Error(
          `${target} already exists. Refusing to overwrite it: on a machine that has ` +
            'been pointed at a real network, these are the deployment\'s actual ' +
            'trust keys, and replacing them with development ones would silently ' +
            'widen what the server accepts. Pass --force if you meant it.',
        );
      }
    }
  }

  await mkdir(outDir, { recursive: true });

  const bundleTmp = `${bundlePath}.tmp`;
  const rootTmp = `${rootPublicKeyPath}.tmp`;

  try {
    // Re-serialising is safe *here specifically*: the root signature covers the
    // canonical bytes of {version, issued_at, keys}, which JSON.stringify's
    // indentation cannot affect. Pretty-printing it makes the file readable to
    // whoever has to reason about which keys a dev server trusts.
    await writeFile(bundleTmp, `${JSON.stringify(bundle, null, 2)}\n`, 'utf8');
    await writeFile(rootTmp, rootPem.endsWith('\n') ? rootPem : `${rootPem}\n`, 'utf8');

    // The server's own loader, with signature checking on, whatever the local
    // environment has TRUST_REQUIRE_SIGNATURE set to.
    const loaded = await loadTrustBundle({
      bundlePath: bundleTmp,
      rootPublicKeyPath: rootTmp,
      requireSignature: true,
    });
    const summary = loaded.summary();

    if (!summary.active_key_count || summary.active_key_count < 1) {
      throw new Error(
        'the bundle loaded and its signature verified, but it holds no active ' +
          'signing key, so the server would answer UNVERIFIABLE to every scan',
      );
    }
    if (
      typeof fixtures.root_fingerprint === 'string' &&
      summary.root_fingerprint !== fixtures.root_fingerprint
    ) {
      throw new Error(
        `root fingerprint mismatch: the bundle declares ${summary.root_fingerprint} ` +
          `and the fixtures declare ${fixtures.root_fingerprint}. The mobile app pins ` +
          'a fingerprint, so a mismatch means phone and server would disagree.',
      );
    }

    await rename(bundleTmp, bundlePath);
    await rename(rootTmp, rootPublicKeyPath);

    return {
      bundlePath,
      rootPublicKeyPath,
      rootFingerprint: summary.root_fingerprint,
      summary,
    };
  } catch (err) {
    // Never leave a half-written pair behind: the next run would find the leftovers
    // and refuse, blaming the operator for this failure.
    await unlink(bundleTmp).catch(() => {});
    await unlink(rootTmp).catch(() => {});
    throw err;
  }
}

// ── Command line ──────────────────────────────────────────────────────────────

const USAGE = `Write backend/keys/ from the test fixtures, for local development.

  npm run dev-keys            create the files, refusing to overwrite
  npm run dev-keys -- --force replace files that are already there

Writes keys/trust-bundle.json and keys/root-public.pem — the two files
assertRuntimePaths() requires before the server will start. Both are public
material: no private key is written and no secret is generated.

The bundle is the same one mobile/assets/trust_bundle.json ships, so a fixture
QR code verifies both offline on the phone and online against the API.

This root is not usable in production. Its private half is generated by a script
in this repository, so anyone can sign a bundle it would accept.`;

async function main() {
  const argv = process.argv.slice(2);
  const force = argv.includes('--force');
  const unknown = argv.filter((a) => a !== '--force' && a !== '--help' && a !== '-h');

  if (argv.includes('--help') || argv.includes('-h')) {
    process.stdout.write(`${USAGE}\n`);
    return;
  }
  if (unknown.length > 0) {
    process.stderr.write(`unknown option ${JSON.stringify(unknown[0])}\n\n${USAGE}\n`);
    process.exitCode = 2;
    return;
  }

  try {
    const out = await materialiseDevKeys({ force });
    const rel = (p) => path.relative(BACKEND_ROOT, p) || p;
    process.stdout.write(
      `${rel(out.bundlePath)}\n${rel(out.rootPublicKeyPath)}\n`,
    );
    process.stderr.write(
      `\nroot fingerprint ${out.rootFingerprint}, ` +
        `${out.summary.active_key_count} active signing key(s) of ${out.summary.key_count}, ` +
        `issued ${out.summary.issued_at}.\nSignature verified with the server's own ` +
        'loader. Development keys only.\n',
    );
  } catch (err) {
    process.stderr.write(`${err?.message ?? String(err)}\n`);
    process.exitCode = 1;
  }
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  await main();
}
